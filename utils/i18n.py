class I18n:
    def __init__(self, lang="zh"):
        self.lang = lang if lang in L else "zh"

    def set_lang(self, lang):
        if lang in L:
            self.lang = lang

    def tr(self, key, *args):
        t = L.get(self.lang, L["zh"]).get(key, key)
        return t.format(*args) if args else t
